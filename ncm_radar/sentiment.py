def _clamp(x, lo=-1.0, hi=1.0):
    return max(lo, min(hi, x))


def score(text: str) -> float:
    """返回 -1 ~ 1 的情绪分。"""
    if not text:
        return 0.0
    t = text.lower()
    total, hits = 0.0, 0

    # 方括号表情标签先算，再从文本里剔除——
    # 否则标签里的「强」「弱」「好」会被情感词典误匹配
    for m in _TAG_RE.finditer(text):
        w = EMOJI_TAGS.get(m.group(1))
        if w is not None:
            total += w
            hits += 1
    t = _TAG_RE.sub(" ", t)

    for word, w in POSITIVE.items():
        idx = t.find(word)
        if idx < 0:
            continue
        val = w
        # 否定翻转
        window = t[max(0, idx - 3):idx]
        if any(n in window for n in NEGATORS):
            val = -val * 0.8
        # 程度副词
        for adv, mult in INTENSIFIERS.items():
            if adv in window:
                val *= mult
                break
        total += val
        hits += 1

    for word, w in NEGATIVE.items():
        idx = t.find(word)
        if idx < 0:
            continue
        val = -w
        window = t[max(0, idx - 3):idx]
        if any(n in window for n in NEGATORS):
            val = -val * 0.8
        for adv, mult in INTENSIFIERS.items():
            if adv in window:
                val *= mult
                break
        total += val
        hits += 1

    # 表情
    total += 0.35 * sum(1 for ch in text if ch in EMOJI_POS)
    total -= 0.35 * sum(1 for ch in text if ch in EMOJI_NEG)

    # 情绪强度信号：感叹号、重复字（啊啊啊 / 哈哈哈哈）
    total += 0.06 * min(text.count("！") + text.count("!"), 4)
    total += 0.04 * len(re.findall(r"(.)\1{2,}", t))

    if hits == 0 and abs(total) < 0.05:
        return 0.0
    # 有命中时按命中数归一，避免长评论刷分
    denom = max(hits, 1) ** 0.65
    return round(_clamp(total / denom), 3)


def label(s: float) -> str:
    for th, name in EMOTION_LABELS:
        if s >= th:
            return name
    return "中性"


# 系统占位文本，不是真实评论
SYSTEM_PATTERNS = ("发布了语音", "该评论已删除", "此评论已被删除",
                   "请前往最新移动端版本查看", "评论包含违规内容")


def extract(comment: dict) -> dict:
    """把一条原始评论压成分析用的结构。"""
    content = (comment.get("content") or "").strip()
    user = comment.get("user") or {}
    valid = bool(content) and not any(p in content for p in SYSTEM_PATTERNS)
    return {
        "id": comment.get("commentId"),
        "text": content,
        "time": comment.get("time", 0),
        "likes": comment.get("likedCount") or 0,
        "user": user.get("nickname") or "匿名",
        "score": score(content),
        "valid": valid,
        "replied": bool(comment.get("beReplied")),
    }
